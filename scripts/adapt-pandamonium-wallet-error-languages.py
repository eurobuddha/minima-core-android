"""Wallet-only diagnostic lookup, adapted from Parlons SystemMessages.

Recognized failures are declared in wallet-errors.json; unknown diagnostics and captured
data remain literal. Exceptions, protocol messages and financial algorithms are unchanged.
"""
from pathlib import Path
import json,re

def build_source(spec, catalog):
    def resource(key):
        assert key in catalog,key
        return 'l10n_'+re.sub(r'([a-z0-9])([A-Z])',r'\1_\2',key).replace('.','_').lower()
    def quote(s):return json.dumps(s,ensure_ascii=False)
    kinds={'number':r'-?[0-9]+(?:\.[0-9]+)?','integer':r'-?[0-9]+','hex':r'0x[0-9a-fA-F]+',
           'boolean':'(?:true|false)','command':'(?:txnimport|txnbasics|txnpost)',
           'literal':r'(?s:.*)','diagnostic':r'(?s:.*)',
           'address':r'(?:0x[0-9a-fA-F]{2,}|M[xX][0-9A-Za-z]{30,100})'}
    patterns=[];resources=[];diagnostic=[]
    for row in spec['patterns']:
        matches=list(re.finditer(r'\{([0-9]+)\}',row['template']))
        assert [int(m[1]) for m in matches]==list(range(len(row['kinds']))),row
        regex='';end=0
        for m,kind in zip(matches,row['kinds']):
            regex+=re.escape(row['template'][end:m.start()])+'('+kinds[kind]+')';end=m.end()
        regex+=re.escape(row['template'][end:])
        patterns.append('        java.util.regex.Pattern.compile('+quote(regex)+')')
        resources.append(resource(row['key']))
        diagnostic.append('{'+','.join('true' if k=='diagnostic' else 'false' for k in row['kinds'])+'}')
    text='''package com.eurobuddha.wallet;

import com.eurobuddha.minimacore.i18n.Language;
import static com.eurobuddha.minimacore.i18n.R.string.*;

/** Explicit wallet failures only. Never use for user content, names, addresses or filenames.
 * Reuses Parlons SystemMessages' fixed lookup, literal captures and bounded diagnostic recursion.
 * Generated by adapt-pandamonium-wallet-error-languages.py from localization/wallet-errors.json. */
public final class WalletMessages {
    private WalletMessages() {}
    public static CharSequence error(Throwable error) {
        if (error == null) return Language.msg(l10n_wallet_operation_failed);
        return message(error.getMessage() == null ? error.toString() : error.getMessage());
    }
    public static CharSequence message(String value) { return message(value,0); }
    private static CharSequence message(String value,int depth) {
        if (value == null) return "";
        if (depth >= 8) return value;
        switch(value) {
'''
    for raw,key in spec['fixed'].items():text+='            case '+quote(raw)+': return Language.msg('+resource(key)+');\n'
    text+='''            default: break;
        }
        for(int i=0;i<PATTERNS.length;i++) {
            java.util.regex.Matcher match=PATTERNS[i].matcher(value);
            if(!match.matches())continue;
            Object[] arguments=new Object[match.groupCount()];
            for(int j=0;j<arguments.length;j++) {
                String literal=match.group(j+1);
                arguments[j]=DIAGNOSTIC[i][j] ? message(literal,depth+1) : literal;
            }
            return Language.msg(RESOURCES[i],arguments);
        }
        return value;
    }
    private static final java.util.regex.Pattern[] PATTERNS={
'''+',\n'.join(patterns)+'''\n    };
    private static final int[] RESOURCES={'''+','.join(resources)+'''};
    private static final boolean[][] DIAGNOSTIC={'''+','.join(diagnostic)+'''};
}
'''
    return text

def adapt(root):
    project=Path(__file__).resolve().parents[1]
    spec=json.loads((project/'localization/wallet-errors.json').read_text())
    catalog=json.loads((project/'localization/catalog.json').read_text())
    text=build_source(spec, catalog)
    base=root/'wallet/src/main/java/com/eurobuddha/wallet'
    (base/'WalletMessages.java').write_text(text)
    for name in ['MainActivity','SendView','NftView','SettingsView']:
        p=base/(name+'.java');s=p.read_text()
        # Display boundaries only. Raw exceptions and callback contracts stay unchanged.
        s=re.sub(r'(Language\.msg\([^;\n]+?), (error|e)\.getMessage\(\)\)',r'\1, WalletMessages.error(\2))',s)
        s=re.sub(r'(Language\.msg\([^;\n]+?), (message)\)',r'\1, WalletMessages.message(\2))',s)
        s=s.replace('Toast.makeText(act, String.valueOf(e.getMessage()),','Toast.makeText(act, WalletMessages.error(e),')
        for context in ['this','act']:
            for var in ['block','error']:
                s=s.replace('Toast.makeText('+context+', '+var+'.getMessage(),','Toast.makeText('+context+', WalletMessages.error('+var+'),')
        s=s.replace('Toast.makeText(act, e.getMessage() == null ? e.toString() : e.getMessage(),','Toast.makeText(act, WalletMessages.error(e),')
        if name=='SettingsView':
            # Node-returned error/JSON fields remain raw. These callbacks are app transport failures.
            s=s.replace('Language.join(Language.msg(l10n_wallet_node_error), ": ", message)',
                        'Language.join(Language.msg(l10n_wallet_node_error), ": ", WalletMessages.message(message))')
        p.write_text(s)
