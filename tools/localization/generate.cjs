// Shared message source. Generated client resources contain all languages offline.
const fs = require('node:fs');
const path = require('node:path');
const root = path.resolve(__dirname, '../..');
const locales = ['en', 'zh-Hans', 'ru', 'uk'];
const source = JSON.parse(fs.readFileSync(path.join(root, 'localization/catalog.json'), 'utf8'));
const messages = Object.fromEntries(locales.map(locale => [locale, {}]));
const placeholders = text => [...text.matchAll(/\{(\w+)\}/g)].map(m => m[1]).sort().join(',');
for (const [key, entry] of Object.entries(source)) {
  if (!/^[a-z][a-zA-Z0-9]*(\.[a-zA-Z0-9]+)+$/.test(key)) throw Error('Invalid message key: ' + key);
  if (Object.keys(entry).sort().join() !== [...locales].sort().join()) throw Error('Incomplete languages: ' + key);
  const reference = typeof entry.en === 'string' ? entry.en : entry.en.other;
  for (const locale of locales) {
    const value = entry[locale];
    if (typeof value !== typeof entry.en) throw Error('Inconsistent plural message: ' + key);
    if (typeof value !== 'string') {
      const categories = new Intl.PluralRules(locale).resolvedOptions().pluralCategories;
      if (categories.some(category => !Object.hasOwn(value, category))) throw Error('Missing plural: ' + key + '/' + locale);
    }
    for (const text of typeof value === 'string' ? [value] : Object.values(value)) {
      if (typeof text !== 'string' || !text.trim()) throw Error('Empty message: ' + key + '/' + locale);
      if (placeholders(text) !== placeholders(reference)) throw Error('Placeholder mismatch: ' + key + '/' + locale);
    }
    messages[locale][key] = value;
  }
}
// Salon statPill renders its number in a separate TextView. These four plural resources
// intentionally contain only the noun; all other plurals retain ImpliedQuantity lint.
const separateCountLabels = new Set(['salonSocial.postCount', 'salonSocial.holdingCount',
  'salonSocial.mediaCount', 'salonSocial.followingCount']);
for (const key of separateCountLabels) if (!Object.hasOwn(source, key) || typeof source[key].en === 'string') throw Error('Missing separate count plural: ' + key);
const outputs = new Map();
// Android's native resource selection and plural rules consume the same catalog.
// Argument order comes from English, so translations can reorder placeholders safely.
const resourceNames = new Set();
const androidName = key => 'l10n_' + key.replace(/([a-z0-9])([A-Z])/g, '$1_$2').replaceAll('.', '_').toLowerCase();
const xml = text => text.replaceAll('&', '&amp;').replaceAll('<', '&lt;').replaceAll('>', '&gt;');
function androidText(text, names) {
  text = text.replaceAll('\\', '\\\\').replaceAll('"', '\\"').replaceAll("'", "\\'").replaceAll('\n', '\\n');
  if (names.length) text = text.replaceAll('%', '%%');
  text = text.replace(/\{(\w+)\}/g, (_, name) => '%' + (names.indexOf(name) + 1) + '$' + (name === 'count' ? 'd' : 's'));
  return '"' + xml(text) + '"';
}
for (const key of Object.keys(source)) {
  const name = androidName(key);
  if (resourceNames.has(name)) throw Error('Duplicate Android resource name: ' + key);
  resourceNames.add(name);
}
for (const locale of locales) {
  const lines = ['<?xml version="1.0" encoding="utf-8"?>', '<!-- Generated by tools/localization/generate.cjs. -->', '<resources xmlns:tools="http://schemas.android.com/tools">'];
  for (const [key, entry] of Object.entries(source)) {
    const reference = typeof entry.en === 'string' ? entry.en : entry.en.other;
    const names = [...new Set([...reference.matchAll(/\{(\w+)\}/g)].map(match => match[1]))];
    const value = entry[locale], name = androidName(key);
    if (names.length) lines.push('    <!-- Arguments: ' + names.join(', ') + ' -->');
    if (typeof value === 'string') lines.push('    <string name="' + name + '"' + (names.length ? '' : ' formatted="false"') + '>' + androidText(value, names) + '</string>');
    else {
      if (separateCountLabels.has(key) && names.length) throw Error('Separate count label acquired arguments: ' + key);
      if (separateCountLabels.has(key)) lines.push('    <!-- Salon statPill displays the numeric count in the adjacent TextView. -->');
      lines.push('    <plurals name="' + name + '"' + (separateCountLabels.has(key) ? ' tools:ignore="ImpliedQuantity"' : '') + '>');
      for (const [quantity, text] of Object.entries(value)) lines.push('        <item quantity="' + quantity + '">' + androidText(text, names) + '</item>');
      lines.push('    </plurals>');
    }
  }
  lines.push('</resources>', '');
  const folder = locale === 'en' ? 'values' : locale === 'zh-Hans' ? 'values-b+zh+Hans' : 'values-' + locale;
  outputs.set('localization/src/main/res/' + folder + '/bear_strings.xml', lines.join('\n'));
}
// Core chat shares the tested diagnostic generator used by the integrated apps.
outputs.set('app/src/main/java/com/eurobuddha/minimacore/chat/ChatMessages.java',
  require('node:child_process').execFileSync('python3', [path.join(root, 'tools/localization/chat-messages.py')], {encoding: 'utf8'}));
for (const [name, contents] of outputs) {
  const file = path.join(root, name);
  if (process.argv.includes('--check')) {
    if (!fs.existsSync(file) || fs.readFileSync(file, 'utf8') !== contents) throw Error('Outdated translations: ' + name);
  } else { fs.mkdirSync(path.dirname(file), { recursive: true }); fs.writeFileSync(file, contents); }
}
console.log(Object.keys(source).length + ' messages validated in ' + locales.length + ' languages');
